export function replaceTokens(
  value: string,
  tokens: Record<string, string | number>,
): string {
  return Object.entries(tokens).reduce(
    (result, [key, token]) => result.split(`{${key}}`).join(String(token)),
    value,
  );
}

export function translateExcludedReason(reason: string, language: Language): string {
  if (language === "zh") return reason;
  const incomplete = reason.match(/去重后 (\d+)\/24/);
  if (incomplete) return `Incomplete hourly candles after deduplication (${incomplete[1]}/24)`;
  if (reason.includes("无法解析") || reason.includes("不合法")) {
    return "Contains an invalid or unparseable candle field";
  }
  if (reason.includes("未严格覆盖")) {
    return "Candles do not strictly cover all 24 hours of one UTC day";
  }
  if (reason.includes("尚未结束")) return "Current UTC day is incomplete and excluded by default";
  if (reason.includes("暂无可用")) return "No usable hourly candles for the current UTC day";
  return reason;
}
